
print("PYTHON MEMBERSHIP OPERATORS")

# Creating a list
subjects = ["Python", "Java", "DBMS", "HTML"]

# Checking values in a list
print("Python in subjects:", "Python" in subjects)
print("C in subjects:", "C" in subjects)

# Checking values not in a list
print("C not in subjects:", "C" not in subjects)
print("Java not in subjects:", "Java" not in subjects)

# Checking characters in a string
language = "Python"

print("P in language:", "P" in language)
print("z in language:", "z" in language)

# Checking keys in a dictionary
student = {"name": "Alex", "marks": 85}

print("name in student:", "name" in student)
print("age in student:", "age" in student)

