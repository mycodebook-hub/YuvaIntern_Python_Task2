
print("PYTHON WHILE LOOP")

# Printing numbers from 1 to 5
number = 1

while number <= 5:
    print(number)
    number += 1

# Calculating the sum of numbers
number = 1
total = 0

while number <= 5:
    total += number
    number += 1

print("Sum of numbers:", total)

print("While Loop Completed")
