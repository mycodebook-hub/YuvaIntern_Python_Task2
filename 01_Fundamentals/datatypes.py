
print("PYTHON DATA TYPES DEMONSTRATION")

# 1. Integer
age = 18
print("Integer:", age)
print("Type:", type(age))

# 2. Float
price = 99.50
print("Float:", price)
print("Type:", type(price))

# 3. Complex
number = 3 + 5j
print("Complex:", number)
print("Type:", type(number))

# 4. String
name = "Python Programming"
print("String:", name)
print("Type:", type(name))

# 5. Boolean
is_available = True
print("Boolean:", is_available)
print("Type:", type(is_available))

# 6. List
subjects = ["Python", "Java", "DBMS"]
print("List:", subjects)
print("Type:", type(subjects))

# 7. Tuple
colors = ("Red", "Blue", "Green")
print("Tuple:", colors)
print("Type:", type(colors))

# 8. Set
numbers = {10, 20, 30}
print("Set:", numbers)
print("Type:", type(numbers))

# 9. Dictionary
student = {"name": "Alex", "marks": 85}
print("Dictionary:", student)
print("Type:", type(student))

# 10. Range
values = range(1, 6)
print("Range:", list(values))
print("Type:", type(values))

# 11. None
result = None
print("None:", result)
print("Type:", type(result))

print("Data Types Demonstration Completed")
