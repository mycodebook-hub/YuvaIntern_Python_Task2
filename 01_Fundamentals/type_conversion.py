
print("PYTHON TYPE CONVERSION")

# 1. Integer to Float
number = 10
result = float(number)
print("Integer to Float:", result)

# 2. Float to Integer
price = 25.75
result = int(price)
print("Float to Integer:", result)

# 3. Integer to String
age = 18
result = str(age)
print("Integer to String:", result)

# 4. String to Integer
value = "100"
result = int(value)
print("String to Integer:", result)

# 5. String to Float
value = "45.5"
result = float(value)
print("String to Float:", result)

# 6. Integer to Boolean
number = 1
result = bool(number)
print("Integer to Boolean:", result)

print("Type Conversion Completed")
