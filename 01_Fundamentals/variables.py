
print("PYTHON VARIABLES DEMONSTRATION")

# Creating variables
student_name = "Alex"
age = 18
marks = 85.5
is_passed = True

print("Student Name:", student_name)
print("Age:", age)
print("Marks:", marks)
print("Passed:", is_passed)

# Checking variable types
print("Name Type:", type(student_name))
print("Age Type:", type(age))
print("Marks Type:", type(marks))
print("Passed Type:", type(is_passed))

# Updating a variable
marks = 90
print("Updated Marks:", marks)

# Multiple variable assignment
a, b, c = 10, 20, 30
print("A:", a)
print("B:", b)
print("C:", c)

# Assigning the same value
x = y = z = 100
print("Same Values:", x, y, z)

# Dynamic typing
value = 50
print("Original Value:", value)

value = "Python"
print("Changed Value:", value)

# Constants
PI = 3.14159
print("PI:", PI)

# Deleting a variable
number = 25
print("Number:", number)
del number

print("Variables Demonstration Completed")
