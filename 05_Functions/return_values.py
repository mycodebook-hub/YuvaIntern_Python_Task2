
print("PYTHON RETURN VALUES")

# Returning addition result
def add_numbers(a, b):
    return a + b

# Returning multiplication result
def multiply_numbers(a, b):
    return a * b

# Returning square of a number
def calculate_square(number):
    return number * number

# Calling functions
addition = add_numbers(10, 20)
multiplication = multiply_numbers(5, 4)
square = calculate_square(6)

print("Addition:", addition)
print("Multiplication:", multiplication)
print("Square:", square)

print("Return Values Completed")
